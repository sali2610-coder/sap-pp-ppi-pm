#!/usr/bin/env node
/* Final Astra status per matrix row, in the completion mandate's vocabulary:
   VERIFIED (a script measured the acceptance on the final export), DONE (applied or
   guidance followed; nothing a script can measure), MANUAL_LIVE_TEST_REQUIRED,
   EXTERNAL_BLOCKER, NOT_APPLICABLE.
   Reads audit/ux-2026-09/COVERAGE-MATRIX.md and the runner's summary.json, writes the
   token into the matrix "מצב סופי" column and the per-row table
   audit/master-completion/ASTRA-FINAL-STATUS.md. Exits 1 on any FAIL row (no final
   status while a measured row fails). */
import { readFileSync, writeFileSync } from "node:fs";

const MATRIX = "audit/ux-2026-09/COVERAGE-MATRIX.md";
const SUMMARY = "audit/master-completion/astra-reverify/summary.json";
const OUT = "audit/master-completion/ASTRA-FINAL-STATUS.md";

// Rows no script can measure: the reason each gets its token.
const NOT_APPLICABLE = {
  "S7-3D-1": "אין תצוגת תלת-ממד בריפו הזה (package.json ללא three/WebGL); קריטריוני הקבלה נבדקו על ה-ERD הדו-ממדי",
  "SCOPE-3": "הצהרת הסוקר על Preview התלת-ממד; ראו S7-3D-1",
  "SCOPE-1": "הצהרת היקף של הסוקר (סקירה רוחבית), אין מה ליישם",
  "SCOPE-4": "הצהרת הסוקר שלא שינה קוד, אין מה ליישם",
};
const MANUAL = {
  "S7-AI-6": "בדיקת AI חיה: אין מפתח שירות בסביבה וקריאות בתשלום דורשות אישור; התסריט ב-audit/ux-2026-09/AI-LIVE-TEST.md",
  "SCOPE-2": "מכשיר פיזי ו-Safari: כל הרצות הטלפון והטאבלט הן Chrome עם UA של iPhone/iPad; הצ'קליסט ב-audit/master-completion/SAFARI-IPHONE-CHECKLIST.md",
};
const EXTERNAL = {};
const DONE_WHY = {
  INS: "שורת הנחיה לקלוד: יושמה במבנה המטריצה ובתהליך",
  PRIO: "שורת עדיפות: ממופה לשורות S שנמדדו",
  S12: "שורת סיכום סבב: הפניות ל-commits",
  "S8-2": "תוכן עניינים מקומי קיים; דרישות קדם אינן בנתונים ולא הומצאו (NOT_IN_DATASET)",
};

const cells = (line) => line.trim().split(/(?<!\\)\|/).slice(1, -1).map((c) => c.trim());
const summary = JSON.parse(readFileSync(SUMMARY, "utf8"));
const runner = Object.fromEntries(summary.rows.map((r) => [r.id, r]));

const lines = readFileSync(MATRIX, "utf8").split("\n");
const out = [], fails = [];
for (let i = 0; i < lines.length; i++) {
  if (!/^\| [A-Z0-9]+[-A-Z0-9]* \|/.test(lines[i])) continue;
  const c = cells(lines[i]);
  if (c.length !== 14) throw new Error(`${MATRIX}:${i + 1}: ${c.length} cells`);
  const id = c[0], r = runner[id];
  if (!r) throw new Error(`${id}: not in ${SUMMARY}`);
  let status, why;
  if (r.result === "PASS") { status = "VERIFIED"; why = `${r.scripts.join(", ") || "runner"}`; }
  else if (r.result === "FAIL") { fails.push(id); status = "FAIL"; why = r.evidence; }
  else if (NOT_APPLICABLE[id]) { status = "NOT_APPLICABLE"; why = NOT_APPLICABLE[id]; }
  else if (MANUAL[id]) { status = "MANUAL_LIVE_TEST_REQUIRED"; why = MANUAL[id]; }
  else if (EXTERNAL[id]) { status = "EXTERNAL_BLOCKER"; why = EXTERNAL[id]; }
  else { status = "DONE"; why = DONE_WHY[id] ?? DONE_WHY[id.split("-")[0]] ?? r.evidence; }
  c[12] = status;
  lines[i] = `| ${c.join(" | ")} |`;
  out.push({ id, section: c[1], status, why });
}
if (fails.length) { console.error(`FAIL rows: ${fails.join(", ")}`); process.exit(1); }
writeFileSync(MATRIX, lines.join("\n"));

const counts = out.reduce((a, r) => ((a[r.status] = (a[r.status] || 0) + 1), a), {});
const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ");
writeFileSync(OUT, [
  "# Astra · final status per row",
  "",
  `Generated by \`scripts/qa/astra-final-status.mjs\` from \`${MATRIX}\` and the runner summary of ${summary.ranAt} (base \`${summary.base}\`). ${out.length} rows: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(" · ")}.`,
  "",
  "VERIFIED = the acceptance was measured by the named script on the final export. DONE = applied or guidance followed, nothing a script can measure. The measurement itself is in the runner summary, never in the status column.",
  "",
  "| id | סעיף | final | basis |",
  "|---|---|---|---|",
  ...out.map((r) => `| ${r.id} | ${esc(r.section)} | ${r.status} | ${esc(r.why)} |`),
  "",
].join("\n"));
console.log(`${out.length} rows · ${JSON.stringify(counts)} → ${OUT}`);
