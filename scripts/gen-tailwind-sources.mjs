#!/usr/bin/env node
// gen-tailwind-sources · Tailwind scans every source file in the repo for class
// names, so the shared stylesheet (app/globals.css, loaded on every page) also
// carried the utilities of the pre-NEO pages, which every address now redirects
// away from: about 7 KB gzip on each /neo page, past the 70 KB CSS budget. This
// writes app/tailwind-sources.css, an `@source not` line for every file under
// app/ and components/ that no page still served imports, directly or through
// other modules. Whatever a served page imports stays scanned, so nothing it
// renders loses a class; lib/ and data/ are always scanned.
//
//   node scripts/gen-tailwind-sources.mjs           write app/tailwind-sources.css
//   node scripts/gen-tailwind-sources.mjs --check   exit 1 if the file is stale
//
// Served = Project NEO (app/neo, components/neo-shell), the root files every
// page renders through (layout, 404, error, loading), the frozen library reader
// and the redesign direction boards (kept pages, see gen-legacy-redirects.mjs).
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = path.join(ROOT, "app", "tailwind-sources.css");
const CHECK = process.argv.includes("--check");
const SOURCE = /\.(tsx?|jsx?|mjs|mdx?|html|json)$/;
const CODE = /\.(tsx?|jsx?|mjs)$/;

const walk = (dir, out = []) => {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, n.name);
    if (n.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
};
const rel = (f) => path.relative(ROOT, f).split(path.sep).join("/");

/* ------------------------------------------------------- the import graph */
const EXT = ["", ".tsx", ".ts", ".jsx", ".js", ".mjs", "/index.tsx", "/index.ts", "/index.js"];
function resolve(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = path.join(ROOT, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(from), spec);
  else return null; // packages
  for (const e of EXT) { const p = base + e; if (existsSync(p) && statSync(p).isFile()) return p; }
  return null;
}
// static imports, re-exports, dynamic import() (next/dynamic, lazy) and require()
const IMPORT = /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+|\brequire\(\s*)["']([^"']+)["']/g;
function closure(entries) {
  const seen = new Set();
  const stack = [...entries];
  while (stack.length) {
    const f = stack.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    if (!CODE.test(f)) continue;
    for (const m of readFileSync(f, "utf8").matchAll(IMPORT)) {
      const r = resolve(f, m[1]);
      if (r && !seen.has(r)) stack.push(r);
    }
  }
  return seen;
}

/* ------------------------------------------------------- what is served */
const at = (...p) => path.join(ROOT, ...p);
const ROOT_FILES = ["layout.tsx", "not-found.tsx", "error.tsx", "global-error.tsx", "loading.tsx", "template.tsx"];
const served = [
  ...walk(at("app", "neo")), ...walk(at("components", "neo-shell")),
  ...ROOT_FILES.map((f) => at("app", f)).filter(existsSync),
  // frozen (CLAUDE.md): the library reader and the shared kit it imports
  ...walk(at("app", "library")), ...walk(at("components", "library")), ...walk(at("components", "neo")),
  at("components", "book-reader.tsx"), at("components", "chapter-reader.tsx"),
  ...walk(at("app", "design", "redesign-2026")),
];
const keep = new Set([...served, ...closure(served.filter((f) => CODE.test(f)))].map(rel));

/* ------------------------------------------------------- what is not */
const excluded = new Set(
  [...walk(at("app")), ...walk(at("components"))].map(rel).filter((f) => SOURCE.test(f) && !keep.has(f)),
);
// A directory none of whose sources is served becomes one line.
const allOut = new Map();
const dirAllOut = (d) => {
  if (!allOut.has(d)) allOut.set(d, walk(at(d)).map(rel).filter((f) => SOURCE.test(f)).every((f) => excluded.has(f)));
  return allOut.get(d);
};
const lines = new Set();
for (const f of excluded) {
  const parts = f.split("/");
  let line = f;
  for (let i = 2; i < parts.length; i++) { const d = parts.slice(0, i).join("/"); if (dirAllOut(d)) { line = d; break; } }
  lines.add(line);
}
// paths are relative to app/, where the generated file lives
const css =
  "/* GENERATED by scripts/gen-tailwind-sources.mjs. Do not edit; rerun it.\n" +
  "   Sources no served page imports, kept out of the shared stylesheet's scan. */\n" +
  [...lines].sort().map((l) => `@source not "${l.startsWith("app/") ? "./" + l.slice(4) : "../" + l}";`).join("\n") + "\n";

if (CHECK) {
  const now = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
  if (now !== css) {
    console.error("app/tailwind-sources.css is stale: run node scripts/gen-tailwind-sources.mjs");
    process.exit(1);
  }
  console.log(`app/tailwind-sources.css is current (${lines.size} lines, ${keep.size} served modules)`);
} else {
  writeFileSync(TARGET, css);
  console.log(`app/tailwind-sources.css: ${lines.size} lines (${excluded.size} files not served; ${keep.size} served modules)`);
}
