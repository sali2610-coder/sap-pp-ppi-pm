#!/usr/bin/env node
/**
 * Generates data/academy/lesson-blocks.generated.ts — a slug → required-block-count map.
 *
 * WHY THIS EXISTS
 *
 * `lib/academy/model.ts` is imported by client components (the academy home,
 * the learning path view, and lib/academy/store.ts). It needed lesson *bodies*
 * for exactly two things:
 *
 *     const has = !!ALL_LESSONS[f.slug];
 *     requiredBlocks: has ? orderedBlocks(ALL_LESSONS[f.slug]).length : 0,
 *
 * an existence check and an integer. To get them it statically imported every
 * generated lesson file — 7.6 MB of authored content — so the whole corpus was
 * shipped to the browser. Measured on production, /academy/ downloaded 4,419 KB
 * of JavaScript, spent 2.2 s executing it, and had a 1,016 ms long task; TBT was
 * 1,750 ms and TTI 24.8 s.
 *
 * This map is the two facts, precomputed. It is ~400 integers. The lesson bodies
 * stay exactly where they were and still load on the lesson pages that render
 * them — nothing about the content, routes or reading experience changes.
 *
 * WHY A GENERATED FILE RATHER THAN A RUNTIME LOOKUP
 *
 * `requiredBlocks` is derived from a lesson's blocks, so it cannot be known
 * without reading the bodies. Computing it at build time is the only way to keep
 * the number correct while keeping the bodies out of the client bundle.
 *
 * Every slug in ALL_LESSONS gets an entry, including lessons whose ordered-block
 * count is 0. That preserves the original `has` semantics exactly: presence in
 * this map means "this slug is a real authored lesson", which is what
 * `!!ALL_LESSONS[slug]` meant. Do not filter zero values out.
 *
 * Runs on plain Node with type stripping — the lesson data files import only
 * types from `@/…`, and those are erased, so no alias resolution, no TypeScript
 * runner and no network are needed. It calls the app's own `orderedBlocks`
 * rather than reimplementing it, so the counts cannot diverge from what the UI
 * would have computed. `npm run check:academy-blocks` fails the build if this
 * file drifts from the lesson data.
 */
import { writeFileSync, readFileSync } from "node:fs";

const OUT = "data/academy/lesson-blocks.generated.ts";

/**
 * `data/academy/lessons/index.ts` composes ALL_LESSONS from sibling modules
 * using extensionless specifiers (`from "./mm-generated"`), which Node's ESM
 * resolver rejects. Rather than hardcode the module list here — which would
 * silently miss a newly added path — read the barrel and re-resolve its own
 * imports with the extension added, preserving order so later spreads win
 * exactly as they do in the barrel.
 */
const barrel = readFileSync("data/academy/lessons/index.ts", "utf8");
const specifiers = [...barrel.matchAll(/from\s+"\.\/([\w-]+)"/g)].map((m) => m[1]);
if (specifiers.length === 0) {
  console.error("gen-academy-blocks: found no sibling imports in data/academy/lessons/index.ts");
  process.exit(1);
}

// The real implementation, not a copy of it — lesson-types.ts has no runtime
// imports, so it loads directly and the counts cannot drift from the app's.
const { orderedBlocks } = await import("../lib/academy/lesson-types.ts");

const ALL_LESSONS = {};
for (const spec of specifiers) {
  const mod = await import(`../data/academy/lessons/${spec}.ts`);
  for (const value of Object.values(mod)) {
    // Each module exports a Record<slug, Lesson> plus a LearningPath; only the
    // former has lesson-shaped values.
    if (value && typeof value === "object" && !Array.isArray(value)) {
      for (const [slug, lesson] of Object.entries(value)) {
        if (lesson && typeof lesson === "object" && Array.isArray(lesson.blocks)) ALL_LESSONS[slug] = lesson;
      }
    }
  }
}

const requiredBlocks = (lesson) => orderedBlocks(lesson).length;

const slugs = Object.keys(ALL_LESSONS).sort();
const entries = slugs.map((s) => `  ${JSON.stringify(s)}: ${requiredBlocks(ALL_LESSONS[s])},`).join("\n");

const body = `// AUTO-GENERATED by scripts/gen-academy-blocks.mjs — DO NOT EDIT BY HAND.
// Regenerate with: npm run gen:academy-blocks
//
// slug -> number of ordered blocks in that lesson. Lets lib/academy/model.ts
// report \`hasLesson\` and \`requiredBlocks\` without importing 7.6 MB of lesson
// bodies into client bundles. A slug is present here if and only if it exists in
// ALL_LESSONS, so \`slug in LESSON_BLOCKS\` is equivalent to the old
// \`!!ALL_LESSONS[slug]\` check — including lessons that have 0 blocks.
export const LESSON_BLOCKS: Record<string, number> = {
${entries}
};
`;

const prev = (() => { try { return readFileSync(OUT, "utf8"); } catch { return null; } })();

if (process.argv.includes("--check")) {
  if (prev !== body) {
    console.error(
      `check-academy-blocks: FAIL — ${OUT} is out of date.\n` +
        `The lesson data changed but the generated block map did not.\n` +
        `Run "npm run gen:academy-blocks" and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`check-academy-blocks: OK — ${slugs.length} lessons, map is in sync.`);
  process.exit(0);
}

writeFileSync(OUT, body);
const zero = slugs.filter((s) => requiredBlocks(ALL_LESSONS[s]) === 0).length;
console.log(`gen-academy-blocks: ${slugs.length} lessons (${zero} with 0 blocks) → ${OUT}`);
